export type ContactRole = 'seller' | 'buyer';

export type ShiftType = 'morning' | 'evening';

export type MilkType = 'buffalo' | 'cow' | 'mix';

export interface Contact {
  id: string;
  name: string;
  role: ContactRole;
  phone: string;
  email?: string;
  defaultRate: number; // PKR per Liter
  morningQuotaLiters?: number;
  eveningQuotaLiters?: number;
  address?: string;
  area?: string;
  latitude?: number;
  longitude?: number;
  // ⚠️ LEGACY: Deprecated for display. Do NOT read in JSX.
  // Compute from entries + payments instead.
  totalLifetimeDue: number; // Cumulative historical debt
  currentMonthDue: number;  // Current month's balance
  avatarColor: string;
  status: 'active' | 'inactive';
  lastActivityTimestamp: string; // e.g. "Today, 07:13 AM" or "01 Oct, 11:38 AM"
  lastActivityIso: string;
  createdAt: string;
  milkTypePref?: 'buffalo' | 'cow' | 'other';
  billCycle?: 'daily' | 'weekly' | 'monthly';
  billDate?: number;
  billTime?: string;
  priceSystem?: 'default' | 'fat_based' | 'formula_based';
  autoAddEntry?: boolean;
  fixedQuantity?: number;
  inactivatedAt?: string; // YYYY-MM-DD date when status became inactive
  reactivatedAt?: string; // YYYY-MM-DD date when status was reactivated
  lastBilledMonth?: string; // YYYY-MM month key when monthly bill was last sent
}

export interface LedgerEntry {
  id: string;
  contactId: string;
  contactName: string;
  contactRole: ContactRole;
  date: string; // YYYY-MM-DD
  timestamp: string; // 24-hr local e.g. "07:13 AM"
  shift: ShiftType;
  milkType: MilkType;
  liters: number; // Decimal precision e.g. 10.5
  ratePerLiter: number; // e.g. 210
  totalAmount: number; // liters * ratePerLiter
  receivedAmount: number; // Cash cleared immediately
  dueAmount: number; // totalAmount - receivedAmount
  fatPercentage?: number; // e.g. 6.5
  snfPercentage?: number; // e.g. 8.8
  paymentMode: 'cash' | 'jazzcash' | 'easypaisa' | 'bank_transfer' | 'credit';
  notes?: string;
  isAutoGenerated?: boolean;
}

